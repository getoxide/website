import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import sharp from "sharp";
import { COPY } from "../src/content/copy.ts";
import { PAGES } from "../src/content/pages.ts";
import {
  OG_CARD_HEIGHT,
  OG_CARD_INPUTS,
  OG_CARD_WIDTH,
  OG_IMAGE,
  OG_MANIFEST,
  ogCardHash,
} from "./og-card.mjs";

const manifest = JSON.parse(readFileSync(OG_MANIFEST, "utf8"));
const png = readFileSync(OG_IMAGE);
const sha256 = (data) => createHash("sha256").update(data).digest("hex");

// Social and share assets #23: one committed card, regenerated by
// `pnpm og:card` whenever the hero copy, the shader, the mark, the fonts or
// the generator changes. A stale card fails here, before the build.
describe("share card", () => {
  it("is fresh: its input hash matches the committed hero copy, shader, mark and fonts", () => {
    expect(manifest.hash).toBe(ogCardHash());
  });

  it("names the exact two lines the card renders", () => {
    expect(manifest.headline).toBe(PAGES.home.h1);
    expect(manifest.subline).toBe(COPY.hero.subheadline);
    expect(manifest.headline).toBe(
      "The complete desktop app for agentic coding.",
    );
  });

  it("lists every input the hash covers", () => {
    expect(manifest.inputs).toEqual(OG_CARD_INPUTS);
    expect(manifest.inputs).toContain("src/lib/hero-shader.ts");
    expect(manifest.inputs).toContain(
      "src/fonts/space-grotesk-latin-wght-normal.woff2",
    );
  });

  it("is the committed 1200×630 PNG the manifest names", async () => {
    const { width, height, format } = await sharp(png).metadata();
    expect({ width, height, format }).toEqual({
      width: OG_CARD_WIDTH,
      height: OG_CARD_HEIGHT,
      format: "png",
    });
    expect(manifest.width).toBe(1200);
    expect(manifest.height).toBe(630);
    expect(manifest.cardSha256).toBe(sha256(png));
  });
});
